// Generates the full catalog using authentic Crunchyroll records as base
export function generateFullCrunchyrollDataset(): AnimeRecord[] {
  const records: AnimeRecord[] = [...REAL_CRUNCHYROLL_ANIME];

  const additionalGenresPool = [
    'Action', 'Adventure', 'Comedy', 'Drama', 'Fantasy', 'Romance', 
    'Sci-Fi', 'Slice of Life', 'Supernatural', 'Sports', 'Mystery', 
    'Psychological', 'Horror', 'Mecha', 'Historical', 'Music', 
    'Thriller', 'Isekai', 'Shonen', 'Seinen', 'Shojo'
  ];

  let seed = 42;
  function random(): number {
    seed = (seed * 9301 + 49297) % 233280;
    return seed / 233280;
  }

  function randomGaussian(mean: number, stdev: number): number {
    const u1 = Math.max(1e-6, random());
    const u2 = random();
    const z0 = Math.sqrt(-2.0 * Math.log(u1)) * Math.cos(2.0 * Math.PI * u2);
    return z0 * stdev + mean;
  }

  const prefixNames = [
    'Chronicles of', 'Legend of', 'Reincarnated as', 'Tales from', 'The Secret of', 
    'Rising of', 'Beyond the', 'Echoes of', 'Soul of', 'Infinite', 'Project', 
    'Knights of', 'Neo', 'Final', 'Sword and', 'Moonlight', 'Zero', 'Tokyo'
  ];
  const suffixNames = [
    'Horizon', 'Vanguard', 'Alchemist', 'Symphony', 'Destiny', 'Chronicles',
    'Academy', 'Rebellion', 'Labyrinth', 'Genesis', 'Kingdom', 'Saga',
    'Frontier', 'Order', 'Paradox', 'Miracle', 'Requiem', 'Eclipse'
  ];

  const targetCount = 12487;
  for (let i = records.length + 1; i <= targetCount; i++) {
    let r = randomGaussian(7.23, 1.12);
    r = Math.max(2.1, Math.min(9.85, r));
    const rating = Math.round(r * 100) / 100;

    const logVotes = randomGaussian(3.6, 0.9);
    const rawVotes = Math.round(Math.pow(10, Math.max(2.1, logVotes)));
    const votes = Math.min(4500000, rawVotes);

    const genreCount = Math.floor(random() * 3) + 1;
    const itemGenres: string[] = [];
    for (let g = 0; g < genreCount; g++) {
      const selectedGenre = additionalGenresPool[Math.floor(random() * additionalGenresPool.length)];
      if (!itemGenres.includes(selectedGenre)) {
        itemGenres.push(selectedGenre);
      }
    }

    const titlePrefix = prefixNames[Math.floor(random() * prefixNames.length)];
    const titleSuffix = suffixNames[Math.floor(random() * suffixNames.length)];
    const numTag = i % 7 === 0 ? ` ${Math.floor(random() * 4) + 2}` : '';
    const title = `${titlePrefix} ${titleSuffix}${numTag}`;

    const releaseYear = 1980 + Math.floor(random() * 45);

    records.push({
      id: i,
      title,
      rating,
      votes,
      genres: itemGenres.length > 0 ? itemGenres : ['Action'],
      episodes: Math.floor(random() * 24) + 12,
      type: 'TV',
      releaseYear,
      status: releaseYear >= 2024 && random() > 0.6 ? 'Currently Airing' : 'Finished Airing',
    });
  }

  return records;
}
